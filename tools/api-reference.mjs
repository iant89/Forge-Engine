#!/usr/bin/env node
/**
 * Generate the consumer-facing API inventory from the reviewed root API snapshot.
 *
 * The declaration files remain the normative signature reference. This page gives consumers one
 * searchable, versioned list of every root export and points to the subsystem guides; keeping the
 * inventory generated prevents the reference page from silently omitting a newly approved symbol.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const snapshotPath = path.join(root, "engine", "api-surface.json");
const outputPath = path.join(root, "docs", "API-REFERENCE.md");
const surface = JSON.parse(fs.readFileSync(snapshotPath, "utf8"));

const common = [
  ["Engine", "runtime host; create it with `Engine.create({ canvas })`"],
  ["Scene", "headless-friendly ECS scene and scene-object owner"],
  ["Entity", "stable scene entity facade; add public component instances"],
  ["Transform", "position, rotation, scale, and hierarchy component"],
  ["Renderer", "WebGPU presentation owner created by the engine"],
  ["VERSION", "package/runtime version string"],
  ["ForgeExtensionRegistry", "1.0 extension catalog and lifecycle owner"],
  ["FORGE_EXTENSION_API_VERSION", "extension contract version"],
];

const subsystemGuides = [
  ["Core runtime", "docs/API.md", "configuration, time, errors, events, logging, tasks, and engine lifecycle"],
  ["Rendering", "docs/RENDERING.md", "materials, geometry, render graph, cameras, lights, and WebGPU setup"],
  ["Terrain", "docs/MARS-TERRAIN.md", "terrain worlds, generators, streaming, materials, and debug tools"],
  ["Physics", "docs/VERIFICATION.md", "physics bodies, shapes, worlds, backends, and debug visualization evidence"],
  ["Scenes and serialization", "docs/SERIALIZATION.md", "scene ownership, components, saves, snapshots, and replay"],
  ["Extensions", "docs/MIGRATION-1.0.md", "the supported 1.0 extension manifest, registry, and registrations"],
  ["Examples", "docs/EXAMPLES.md", "reviewed runnable root-import examples"],
  ["Compatibility", "docs/VERSIONING.md", "semver, release gates, and version consistency"],
];

function tableCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

const counts = surface.counts;
const lines = [
  "# @forge/engine API reference",
  "",
  "> Generated by `npm run api:reference` from `engine/api-surface.json`. The package declaration files",
  "> are the normative source for full signatures; this inventory is the consumer-facing index and is",
  "> checked against the root-only API audit. Do not import a symbol from a deep path because it appears",
  "> in an implementation file.",
  "",
  "## Import boundary",
  "",
  "```ts",
  'import { Engine, Scene, VERSION } from "@forge/engine";',
  "```",
  "",
  "Only `@forge/engine` is supported. The current reviewed surface contains " + counts.total.toLocaleString("en-US")
    + " exports: " + counts.public.toLocaleString("en-US") + " public, " + counts.experimental
    + " experimental, and " + counts.deprecated + " deprecated. The snapshot is for package version `"
    + surface.packageVersion + "` and uses declaration-contract fingerprints; a hash is not a substitute "
    + "for reading the signature and behavior documentation.",
  "",
  "## Start here",
  "",
  "| Symbol | Consumer role |",
  "| --- | --- |",
];
for (const [name, role] of common) lines.push(`| \`${name}\` | ${role} |`);
lines.push(
  "",
  "## Subsystem guides",
  "",
  "| Area | Guide | Scope |",
  "| --- | --- | --- |",
);
for (const [area, guide, scope] of subsystemGuides) lines.push(`| ${area} | [${guide}](../${guide}) | ${scope} |`);
lines.push(
  "",
  "## Stability markers",
  "",
  "- **public**: approved for the 1.0 consumer contract.",
  "- **experimental**: explicitly opt-in and excluded from normal compatibility guarantees; read the release notes before using it.",
  "- **deprecated**: retained during the window in [DEPRECATION.md](DEPRECATION.md), with a replacement in the migration notes.",
  "",
  "## Complete root export inventory",
  "",
  "The rows below are sorted by exported name. `declarationHash` identifies the direct exported "
    + "declaration; `contractHash` includes engine-local declaration dependencies. They let review tooling "
    + "detect a signature/member/type change. The emitted `.d.ts` file, API guides, and tests explain how a "
    + "symbol behaves; consumers should not treat hashes as callable signatures.",
  "",
  "| Name | Kind | Stability | Declaration hash | Contract hash |",
  "| --- | --- | --- | --- | --- |",
);
for (const item of surface.exports) {
  lines.push(`| \`${tableCell(item.name)}\` | ${item.kind} | ${item.stability} | \`${item.declarationHash}\` | \`${item.contractHash}\` |`);
}
lines.push(
  "",
  "## Updating this page",
  "",
  "When a public export changes, update the implementation and consumer docs first, run `npm run api:update`, "
    + "review the approval ledger, then run `npm run api:reference`. The API audit and approval gate must be "
    + "green before a release. A generated row does not approve an API addition.",
  "",
);

const expected = `${lines.join("\n")}\n`;
if (check) {
  const actual = fs.readFileSync(outputPath, "utf8");
  if (actual !== expected) {
    console.error("api:reference:check FAILED — docs/API-REFERENCE.md is stale; run npm run api:reference");
    process.exitCode = 1;
  } else {
    console.log(`api:reference:check OK — ${surface.exports.length.toLocaleString("en-US")} exports are documented`);
  }
} else {
  fs.writeFileSync(outputPath, expected);
  console.log(`api:reference OK — wrote ${surface.exports.length.toLocaleString("en-US")} exports to docs/API-REFERENCE.md`);
}
